"""Build web/qutie.js, the JavaScript library, from js/ and the Studio's engine.

    uv run python tools/build_js.py          # writes js/barcode-tables.js and web/qutie.js
    uv run python tools/build_js.py --check  # fails if they are not up to date (tests use it)

The library draws labels with the Studio's own engine (web/designer/model.js, data.js,
render.js), wrapped in a function with what the Studio's window gives it otherwise: the
strings it needs, the language, and the codes (from js/codes.js instead of Python). The
barcode tables come from python-barcode, so the bars are the same as the Studio's.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ENGINE = ROOT / "src" / "qutie" / "app" / "web" / "designer"
JS = ROOT / "js"
OUT = ROOT / "web" / "qutie.js"
TABLES = JS / "barcode-tables.js"


def barcode_tables() -> str:
    import barcode
    from barcode.charsets import codabar, code39, code128, ean, itf, upc

    tables = {
        "code128": {
            "ALL": "".join(sorted(c for c in code128.ALL if len(c) == 1)),
            "A": code128.A, "B": code128.B, "C": code128.C, "CODES": list(code128.CODES),
            "STOP": code128.STOP, "START": code128.START_CODES, "TO": {str(k): v for k, v in code128.TO.items()},
        },
        "code39": {"MAP": {k: [v[0], v[1]] for k, v in code39.MAP.items()}, "EDGE": code39.EDGE, "MIDDLE": code39.MIDDLE},
        "ean": {"EDGE": ean.EDGE, "MIDDLE": ean.MIDDLE, "CODES": {k: list(v) for k, v in ean.CODES.items()},
                "LEFT_PATTERN": list(ean.LEFT_PATTERN)},
        "upc": {"EDGE": upc.EDGE, "MIDDLE": upc.MIDDLE, "CODES": {k: list(v) for k, v in upc.CODES.items()}},
        "itf": {"START": itf.START, "STOP": itf.STOP, "CODES": list(itf.CODES)},
        "codabar": {"CODES": codabar.CODES, "STARTSTOP": codabar.STARTSTOP},
    }
    version = getattr(barcode, "__version__", "?")
    return (f"// Generated by tools/build_js.py from python-barcode {version}: do not edit.\n"
            f"const BARCODE_TABLES = {json.dumps(tables, ensure_ascii=True, separators=(',', ':'))};\n")


# Strings the engine shows on labels; the rest of the Studio's strings are not needed here.
WORDS = {
    "en": {"yes": "yes", "no": "no", "untitled": "Label", "column": "Column", "dataTableName": "Table", "type_text": "Text"},
    "it": {"yes": "sì", "no": "no", "untitled": "Etichetta", "column": "Colonna", "dataTableName": "Tabella", "type_text": "Testo"},
    "es": {"yes": "sí", "no": "no", "untitled": "Etiqueta", "column": "Columna", "dataTableName": "Tabla", "type_text": "Texto"},
    "fr": {"yes": "oui", "no": "non", "untitled": "Étiquette", "column": "Colonne", "dataTableName": "Tableau", "type_text": "Texte"},
    "de": {"yes": "ja", "no": "nein", "untitled": "Etikett", "column": "Spalte", "dataTableName": "Tabelle", "type_text": "Text"},
    "pt": {"yes": "sim", "no": "não", "untitled": "Etiqueta", "column": "Coluna", "dataTableName": "Tabela", "type_text": "Texto"},
    "ru": {"yes": "да", "no": "нет", "untitled": "Этикетка", "column": "Столбец", "dataTableName": "Таблица", "type_text": "Текст"},
    "zh": {"yes": "是", "no": "否", "untitled": "标签", "column": "列", "dataTableName": "表格", "type_text": "文本"},
    "ja": {"yes": "はい", "no": "いいえ", "untitled": "ラベル", "column": "列", "dataTableName": "表", "type_text": "テキスト"},
}

ENGINE_HEAD = """const engine = (() => {
  // What the Studio's window gives its engine: language, strings and codes.
  const LOCALES = { en: "en-GB", it: "it-IT", es: "es-ES", fr: "fr-FR", de: "de-DE", pt: "pt-PT", ru: "ru-RU", zh: "zh-CN", ja: "ja-JP" };
  const WORDS = __WORDS__;
  let LANG = "en", LOCALE = "en-GB", LOCALE_DECIMAL = ".", words = WORDS.en;
  function setLocale(tag) {
    const t = String(tag || "en").replace("_", "-");
    LANG = t.slice(0, 2).toLowerCase() in LOCALES ? t.slice(0, 2).toLowerCase() : "en";
    LOCALE = t.length > 2 && t.slice(0, 2).toLowerCase() === LANG ? t : LOCALES[LANG];
    try { LOCALE_DECIMAL = (1.5).toLocaleString(LOCALE).charAt(1) || "."; } catch { LOCALE_DECIMAL = "."; }
    words = WORDS[LANG];
  }
  // Formula errors and the like: readable even without the Studio's translations.
  const T = new Proxy({}, { get: (_, key) => (key in words ? words[key] : typeof key === "string" && key.startsWith("fx") ? (...a) => [key.slice(2), ...a].join(": ") : String(key)) });
  async function api(name, ...args) {
    if (name !== "codes") throw new Error(`${name} is not available in the library`);
    const [kind, content, options = {}] = args;
    return kind === "qr" || kind === "microqr"
      ? qrModules(content, { micro: kind === "microqr", ecc: options.ecc, version: options.version })
      : barcodeModules(kind, content);
  }
"""

ENGINE_TAIL = """
  setLocale(typeof navigator !== "undefined" ? navigator.language : "en");
  return {
    setLocale, normalizeDocument, newDocument, newData, makeObject, quickDocument, labelPlan, renderPlan, rasterize,
    mediaOf, labelLength, labelFeed, bitsToCanvas, fieldNames, fieldsIn, TAPE_MM, FEED_GAP, FEED_CONTINUOUS,
    layoutFor, expandAll, codeKind, codeOpts,
  };
})();
"""


def indent(text: str) -> str:
    return "".join(f"  {line}" if line.strip() else line for line in text.splitlines(keepends=True))


def bundle() -> str:
    from qutie import __version__

    engine = ENGINE_HEAD.replace("__WORDS__", json.dumps(WORDS, ensure_ascii=False))
    for name in ("model.js", "data.js", "render.js"):
        engine += f"\n  // ---- Qutie Studio: web/designer/{name}\n" + indent((ENGINE / name).read_text(encoding="utf-8"))
    engine += ENGINE_TAIL
    parts = [
        f"/*! qutie.js {__version__}: print on the HPRT Qutie label maker from the browser (Web Bluetooth, Web Serial).\n"
        " * MIT License. https://github.com/DoctorFrank28/qutie-windows\n"
        " * Generated by tools/build_js.py from js/ and Qutie Studio's engine: do not edit. */\n",
        TABLES.read_text(encoding="utf-8"),
        (JS / "codes.js").read_text(encoding="utf-8"),
        (JS / "protocol.js").read_text(encoding="utf-8"),
        engine,
        (JS / "printer.js").read_text(encoding="utf-8").replace("__VERSION__", __version__),
        "\nexport { Qutie, Printer, QutieError, labelJob, parseStatus, parseInfo };\nexport default Qutie;\n",
    ]
    return "\n".join(p.replace("\r\n", "\n") for p in parts)


def main(argv: list[str]) -> int:
    tables, library = barcode_tables(), None
    if "--check" in argv:
        library = bundle() if TABLES.read_text(encoding="utf-8").replace("\r\n", "\n") == tables else None
        current = OUT.read_text(encoding="utf-8").replace("\r\n", "\n") if OUT.exists() else ""
        if library is None or current != library:
            print("web/qutie.js is out of date: run uv run python tools/build_js.py", file=sys.stderr)
            return 1
        return 0
    TABLES.write_text(tables, encoding="utf-8", newline="\n")
    OUT.write_text(bundle(), encoding="utf-8", newline="\n")
    print(f"{OUT.relative_to(ROOT)}: {OUT.stat().st_size // 1024} KB")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
